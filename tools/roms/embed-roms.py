#!/usr/bin/env python3
"""Generate roms_embedded.c: the recognised BIOS images in a directory, or
nothing at all.

The RCA Studio II BIOS is copyrighted RCA firmware and is not redistributed
by this project (COMPLIANCE.md). --none is therefore the SHIPPING
configuration, not an error path: it emits an empty table, and the machine
boots CONFIG on the app's own stand-in.

With a directory (WITH_STUDIO2_ROMS=ON, a developer build), every file in it
whose size and CRC-32 match MAME's table (core/src/roms.c) is embedded under
MAME's file name, whatever it is called locally. Anything else is ignored.

usage: embed-roms.py <out.c> <dir>
       embed-roms.py --none <out.c>
"""

import sys
import zlib
from pathlib import Path

# (size, crc) -> MAME's file name; mirrors s_bios[] in core/src/roms.c
KNOWN = {
    (0x800, 0xA494B339): "studio2.bin",
    (0x400, 0xD3DE048C): "studio2-system.bin",
    (0x200, 0x283B7E65): "84932.ic11",
    (0x200, 0xA396B77C): "84933.ic12",
    (0x200, 0xD25CF97F): "85456.ic13",
    (0x200, 0x74AA724F): "85457.ic14",
}

HEADER = """/* Generated by tools/roms/embed-roms.py -- do not edit.
 * SPDX-License-Identifier: GPL-3.0-or-later
 */
#include "roms_embedded.h"

"""


def main():
    args = sys.argv[1:]
    if args and args[0] == "--none":
        if len(args) != 2:
            sys.exit(__doc__)
        Path(args[1]).write_text(
            HEADER
            + "/* Nothing embedded -- the shipping configuration. */\n"
            + "const studio2_embedded_rom studio2_embedded_roms[1] = { { 0, 0, 0 } };\n"
            + "const unsigned studio2_embedded_rom_count = 0;\n")
        return 0

    if len(args) != 2:
        sys.exit(__doc__)
    out, src = Path(args[0]), Path(args[1])
    found = {}
    for f in sorted(src.iterdir()) if src.is_dir() else []:
        if not f.is_file() or f.stat().st_size > 0x800:
            continue
        data = f.read_bytes()
        name = KNOWN.get((len(data), zlib.crc32(data) & 0xFFFFFFFF))
        if name and name not in found:
            found[name] = data

    body = [HEADER,
            "/* WITH_STUDIO2_ROMS=ON: a developer build. NOT redistributable.\n"
            " * See COMPLIANCE.md. */\n"]
    for i, (name, data) in enumerate(found.items()):
        body.append("static const uint8_t rom%d[%d] = {\n" % (i, len(data)))
        for j in range(0, len(data), 16):
            body.append("    " + ",".join("0x%02X" % b for b in data[j:j + 16]) + ",\n")
        body.append("};\n")
    body.append("\nconst studio2_embedded_rom studio2_embedded_roms[%d] = {\n" % max(1, len(found)))
    for i, (name, data) in enumerate(found.items()):
        body.append('    { "%s", rom%d, %d },\n' % (name, i, len(data)))
    if not found:
        body.append("    { 0, 0, 0 },\n")
    body.append("};\nconst unsigned studio2_embedded_rom_count = %d;\n" % len(found))
    out.write_text("".join(body))
    print("embed-roms: %d image(s): %s" % (len(found), ", ".join(found) or "none"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
