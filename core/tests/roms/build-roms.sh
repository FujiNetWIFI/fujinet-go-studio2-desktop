#!/usr/bin/env bash
# build-roms.sh -- assemble the tests' images (Macroassembler AS) into
# ../test_rom.h. Run it after editing an .asm here; the header is committed
# so the tests build without an assembler.
set -euo pipefail
cd "$(dirname "$0")"
ASL=${ASL:-$HOME/asl/asl}
P2BIN=${P2BIN:-$(dirname "$ASL")/p2bin}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
cp counter.asm testbios.asm "$tmp/"
(cd "$tmp"
 "$ASL" -q -U -L -o app.p -olist app.lst -D COUNTER_APP counter.asm && "$P2BIN" -q -r '$0400-$07FF' app.p app.bin
 "$ASL" -q -U -o game.p counter.asm && "$P2BIN" -q -r '$0400-$07FF' game.p game.bin
 "$ASL" -q -U -o bios.p testbios.asm && "$P2BIN" -q -r '$0000-$07FF' bios.p bios.bin)
python3 - "$tmp" > ../test_rom.h <<'PY'
import sys, os
d = sys.argv[1]
def arr(name, path):
    b = open(os.path.join(d, path), 'rb').read()
    out = ["static const unsigned char %s[%d] = {" % (name, len(b))]
    for i in range(0, len(b), 12):
        out.append("    " + " ".join("0x%02X," % x for x in b[i:i+12]))
    out.append("};")
    return "\n".join(out)
print("""/* test_rom.h -- GENERATED by roms/build-roms.sh from roms/*.asm; do not edit.
 *
 * test_counter_app:  counter.asm with the FujiNet claim, 1K at $0400 (raw)
 * test_counter_game: the same without it (a game: needs a BIOS)
 * test_bios:         testbios.asm, 2K (a BIOS of the tests' own)
 *
 * Copyright (C) 2026 Thomas Cherryhomes
 * SPDX-License-Identifier: GPL-3.0-or-later
 */
#ifndef STUDIO2_TEST_ROM_H
#define STUDIO2_TEST_ROM_H

#include <stdio.h>

#define TEST_RAM_COUNTER 0x0810
#define TEST_RAM_KEY1    0x0811
#define TEST_RAM_IRQS    0x0812
""")
# the counter's labels, from the listing's symbol table (" name : hex C |")
import re
lst = open(os.path.join(d, "app.lst")).read()
syms = sorted(set(re.findall(r"\*?(\w+) :\s+([0-9A-F]+) C \|", lst)), key=lambda x: int(x[1], 16))
for name, val in syms:
    print("#define TEST_COUNTER_%s 0x%04X" % (name.upper(), int(val, 16)))
print()
print(arr("test_counter_app", "app.bin"))
print(arr("test_counter_game", "game.bin"))
print(arr("test_bios", "bios.bin"))
print("""
/* Write one of them (or `size` bytes of filler when data is NULL) to path.
 * Returns the bytes written, or -1. */
static long test_rom_write(const char *path, const unsigned char *data, long size)
{
    FILE *f = fopen(path, "wb");
    long i;
    if (!f)
        return -1;
    for (i = 0; i < size; i++)
        fputc(data ? data[i] : (int)((i * 7 + 3) & 0xff), f);
    fclose(f);
    return size;
}

#endif /* STUDIO2_TEST_ROM_H */""")
PY
echo "wrote ../test_rom.h"
